/** O retrato da loja, em numeros, a partir do disco. */
export function retrato(raiz = RAIZ) {
  const nomes = readdirSync(join(raiz, 'Apps'), { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => a.localeCompare(b))
  const conflitos = mapaDeConflitos(nomes)
  const evidPath = join(raiz, 'docs', 'evidence', 'boot.json')
  const evid = existsSync(evidPath) ? JSON.parse(readFileSync(evidPath, 'utf8')) : { apps: {}, runs: [] }
  const apps = nomes.map((nome) => {
    const doc = yaml.load(readFileSync(join(raiz, 'Apps', nome, 'docker-compose.yml'), 'utf8'))
    const x = doc['x-casaos'] || {}
    const xr = doc['x-roqueos'] || {}
    const p = premissas(carregar(nome), conflitos)
    const abertas = Object.entries(p).filter(([, v]) => v.length).map(([k]) => k)
    const gerar = Object.values(xr.gerar || {})
    return {
      nome,
      categoria: Array.isArray(x.category) ? x.category[0] : x.category,
      arquiteturas: x.architectures || [],
      servicos: Object.keys(doc.services || {}).length,
      segredos: gerar.length,
      mostra: gerar.some((s) => s && s.mostrar),
      senhaPadrao: Boolean(xr.senhaPadraoDaImagem),
      abertas,
      boot: evid.apps[nome] || null,
    }
  })
  const aposentados = join(raiz, 'docs', 'pt-BR', 'APOSENTADOS.md')
  const linhasSaida = existsSync(aposentados)
    ? readFileSync(aposentados, 'utf8').split('\n').filter((l) => /^\| [A-Z][^|]* \|/.test(l) && !/^\| App \|/.test(l))
    : []
  // Uma linha pode citar mais de um app ("Logseq, InvoiceNinja, Authelia"): conta os nomes.
  const saidas = linhasSaida
    .map((l) => l.split('|')[1].split(',').map((n) => n.trim()).filter(Boolean).length)
    .reduce((a, b) => a + b, 0)
  return { apps, runs: evid.runs || [], saidas }
}

const contar = (lista, f) => lista.filter(f).length

function porCategoria(apps) {
  const m = new Map()
  for (const a of apps) m.set(a.categoria, (m.get(a.categoria) || 0) + 1)
  return [...m.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
}

