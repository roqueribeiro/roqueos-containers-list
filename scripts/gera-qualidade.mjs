/** O Markdown de um idioma. Puro: mesma entrada, mesmo texto. */
export function pagina(r, l) {
  const t = T[l]
  const a = r.apps
  const runLink = (n) => `[${n}](https://github.com/roqueribeiro/roqueos-containers-list/actions/runs/${n})`
  return [
    t.titulo,
    '',
    t.outro,
    '',
    t.gerado,
    '',
    t.resumo,
    '',
    tabela([t.item, t.valor, t.fonte], t.linhas(r, a)),
    '',
    t.runs,
    '',
    t.runsTexto,
    '',
    tabela(t.runCab, r.runs.map((x) => [runLink(x.run), x.quando])),
    '',
    t.cat,
    '',
    tabela(t.catCab, porCategoria(a).map(([c, n]) => [c, String(n)])),
    '',
    t.porApp,
    '',
    tabela(
      t.porAppCab,
      a.map((x) => [
        `[${x.nome}](${l === 'en' ? '../' : '../../'}Apps/${x.nome}/README.md)`,
        x.categoria || '',
        x.arquiteturas.join(', '),
        String(x.servicos),
        x.segredos ? `${x.segredos}${x.mostra ? ' (' + t.sim + ')' : ''}` : t.nao,
        x.boot ? t.boot(x.boot) : t.semBoot,
        x.abertas.length ? x.abertas.join(', ') : t.fechadas,
      ]),
    ),
    '',
  ].join('\n')
}

const isCli = import.meta.url === pathToFileURL(process.argv[1] || '').href
if (isCli) {
  const r = retrato()
  const check = process.argv.includes('--check')
  let velho = 0
  for (const l of ['en', 'pt']) {
    const texto = pagina(r, l)
    const atual = existsSync(SAIDAS[l]) ? readFileSync(SAIDAS[l], 'utf8') : ''
    if (check) {
      if (atual !== texto) {
        console.error(`desatualizado: ${SAIDAS[l].replace(RAIZ + '/', '')} (rode yarn docs:quality)`)
        velho++
      }
    } else writeFileSync(SAIDAS[l], texto)
  }
  if (check && velho) process.exit(1)
  if (!check) console.log(`${r.apps.length} apps; paginas gravadas em docs/QUALITY.md e docs/pt-BR/QUALIDADE.md`)
}
